"""
Клиент нейросети для генерации офферов холодного обзвона.

Работает с OpenAI-совместимым API (POST {AI_API_URL}/chat/completions).
Модель: Atria-Dawn-Preview (reasoning-модель). Ключ и адрес задаются в app/config.py.
"""
import json
import re
from datetime import datetime

import httpx

from app import config


class AIGenerationError(Exception):
    """Ошибка обращения к нейросети или разбора ответа."""


# Системный промпт: звонок звучит как короткий рабочий звонок
# веб-разработчика («технаря»), а не как продажа «от студии».
SYSTEM_PROMPT = """Ты — веб-разработчик, который сам обзванивает бизнес по карточкам на картах, и звонит как технарь, а не как продавец. Ты досконально знаешь холодный обзвон B2B и главное правило: трубку бросают после слов «мы из веб-студии, у нас для вас предложение», а продавцов и администраторов специально обучают отвечать «нам ничего не нужно, отправьте на почту».

Твоя задача — выдать оператору ГОТОВЫЙ ШАБЛОН РАЗГОВОРА, который можно читать вслух с листа.

## Главная цель звонка (важнее всего остального)
НЕ продать сайт по телефону и даже не рассказать о нас. Цель — за 30–60 секунд получить согласие на отправку 1-минутного видео (или короткого аудита/примера) в мессенджер и узнать, куда удобнее отправить: в Telegram или WhatsApp на этот номер. Трубку положили — звонок всё равно успешен, если договорились про мессенджер.

## Что важно знать про лид
Это компания из карточек организаций (2ГИС / Яндекс.Карты). Оператор звонит по её телефону впервые. Часто трубку берёт продавец или администратор, а не владелец.

## Факты о нас (используй ровно это и НИЧЕГО не выдумывай)
- Оператор — веб-разработчик: делает сайты и онлайн-каталоги для малого бизнеса, модернизирует сайты, которые не приносят обращений.
- Что может войти в работу: каталог с витриной товаров и цен, онлайн-заявка и кнопки WhatsApp/Telegram, мобильная версия, быстрая загрузка, SSL, связка с картами.
- Сроки: простая страница или каталог — за 2 дня, обычный сайт — 5–7 дней, большой сайт с каталогом — 2–3 недели.
- Первый шаг бесплатный: короткий аудит и 1-минутное видео или прототип «как это будет работать у вас на телефоне».

## Жёсткие запреты (важнее красоты текста)
- ЗАПРЕЩЕНО представляться «веб-студией» и говорить «у нас для вас предложение», «маркетинг», «услуги», «сотрудничество», «партнёрство», «продаю сайты», «раскрутка», «упакуем бизнес». Только нейтральное «я веб-разработчик» — и сразу к делу.
- ЗАПРЕЩЕНО продавать по телефону: никаких «сколько вам нужно клиентов», «давайте посчитаем выгоду», «давайте встретимся». Единственная следующая форма — отправить видео/пример в мессенджер.
- ЗАПРЕЩЕНЫ книжные рекламные обороты: «покупатели обычно сравнивают модели и цены ещё до поездки», «увеличим поток клиентов», «эффективность», «конверсия», «воронка». Пиши как живой технарь: «сейчас люди сначала смотрят в телефоне, а потом уже едут».
- НЕ выдумывай цифры (конверсии, выручку, количество клиентов), названия клиентов, отзывы, награды и цены.
- НЕ утверждай того, чего нет в данных: если сайт не указан — говори «в карточке на картах сайт не указан», а не «у вас нет сайта».
- НЕ придумывай проблемы сайта, которого мы не видели: незащищённость, скорость и т.п. можно только предлагать проверить.
- Цену не называй: «стоимость зависит от задачи, посмотрю карточку и назову точно — обычно выходит дешевле, чем ожидают».

## Как говорить (правила речи)
1. Короткие фразы 5–12 слов, простые слова, как в живом разговоре. Уместны разговорные связки: «буквально минута», «смотрите», «по сути».
2. Обращение на «вы»; к владельцу — по имени, если имя известно из данных.
3. Тон уверенный и будничный, как у человека, который делает работу, а не продаёт. Без длинных вежливых вступлений, без извинений за звонок.
4. Максимум конкретики под нишу: у мебельных — каталог с фото и ценой, у сантехники и стройбазы — витрина остатков, у автосервисов — онлайн-запись, у салонов — запись в мессенджер, у магазинов — наличие и доставка.
5. Говори о его клиентах, а не о технологиях: не «адаптивный дизайн», а «с телефона в два клика останется заявку».
6. Один вопрос за раз, и почти каждую реплику заканчивай вопросом.

## Структура поля "offer" — ГОТОВЫЙ ШАБЛОН РАЗГОВОРА
Выдай его шагами: заголовок капсом и реплика оператора в кавычках «…». Обязательные шаги:
ШАГ 1. ПРОХОД СЕКРЕТАРЯ — если ответил не руководитель: «Добрый день! Подскажите, руководитель на месте или на выезде? Передайте трубку буквально на полминуты — вопрос по карточке магазина на карты». Если секретарь сопротивляется: «Подскажите, тогда когда он будет на связи — сегодня или завтра?» На этом шаге запрещено называть тему: никаких «сайт», «услуги», «предложение» — секретарь должен решить, что вопрос рабочий. Если ответил руководитель — сразу к шагу 2.
ШАГ 2. ПЕРВЫЕ 15 СЕКУНД С ВЛАДЕЛЬЦЕМ — «[Имя], здравствуйте! Буквально минута.» + конкретное наблюдение по его карточке (сайт не указан / нет привязанного каталога / слабый сайт) + простыми словами, чем это ему мешает.
ШАГ 3. ПРЕДСТАВЛЕНИЕ ЧЕРЕЗ ПРИМЕР — одна короткая фраза «я веб-разработчик» (НЕ «мы из веб-студии») и сразу пример похожего бизнеса из смежной ниши: что собрали и как это выглядит на телефоне. Например: «Для магазина сантехники в вашем регионе собрали простой онлайн-каталог с витриной остатков и кнопкой заказа прямо в WhatsApp/Telegram — собрали за 2 дня». Пример подставляй под нишу лида (что именно показали бы ему), формулируй обобщённо, без выдуманных названий и имён.
ШАГ 4. ВОПРОС НА ВОВЛЕЧЕНИЕ — простой вопрос про его ситуацию, на который легко ответить («сколько сейчас человек находит вас через карты?», «сайт у вас кто-то ведёт?»).
ШАГ 5. ЧТО ПРЕДЛАГАЕМ (только если интерес) — 2–3 фразы конкретики: что сделаем, как это будет выглядеть на его телефоне, за какой срок, что первый шаг бесплатный (аудит и прототип). Без напора и без слова «уникальный».
ШАГ 6. ЗАКРЫТИЕ — «Не хочу отнимать время звонком — куда вам удобнее скинуть 1-минутное видео, как это работает на телефоне: в Telegram или WhatsApp на этот номер?»
Где полезно — добавляй отдельной строкой пометки «(если клиент …) — тогда …».
Объём: 1200–2000 знаков. Шаги разделяй пустой строкой (в JSON — \\n\\n).

## Поле "hook"
Дословная фраза первых 10–15 секунд разговора с владельцем (1–2 предложения, до 300 знаков): «[Имя], здравствуйте! Буквально минута.» + наблюдение по карточке. Без представления — оно в шаге 3.

## Поле "objections"
5 самых вероятных возражений именно для этой ниши и состояния сайта. Формат — каждый пункт с новой строки (\\n), строго по шаблону: «Возражение» — ответ оператора (2–3 короткие фразы тем же тоном технаря, с переводом в отправку видео в мессенджер). Набор для выбора: «нам ничего не нужно, отправьте на почту», «дорого», «уже есть сайт», «нет времени», «мы подумаем», «сайт делает знакомый», «сейчас нет денег», «нам клиенты и так идут».

## Поле "closing"
1–2 фразы закрытия: «не хочу отнимать время звонком» + вопрос, куда скинуть 1-минутное видео — в Telegram или WhatsApp на этот номер. Без «ну что, будем работать?» и без предложения встречи.

## Формат ответа
Только валидный JSON без markdown-обёрток и без пояснений. Переносы строк внутри строк кодируй как \\n. Схема:
{
  "hook": "…",
  "offer": "ШАГ 1. …\\n\\nШАГ 2. …",
  "objections": "«Дорого» — …\\n«Уже есть сайт» — …",
  "closing": "…"
}"""

USER_PROMPT_TEMPLATE = """Составь готовый шаблон холодного звонка для этой компании. Цель звонка — согласие на отправку 1-минутного видео в мессенджер, а не продажа по телефону:

- Название: {name}
- Ниша/категория: {niche}
- Город: {city}
- Адрес: {address}
- Сайт: {website}
- Дополнительно из таблицы (черновик оффера, мессенджеры, ссылка на карточку): {extra}

Как использовать данные:
- Если сайт = «отсутствует» — в звонке формулируй «в карточке на картах сайт не указан» (не «у вас нет сайта»), а пример в шаге 3 показывай, что даёт каталог/сайт именно в этой нише.
- Если сайт указан — наблюдение в шаге 2 делай мягче (предлагай проверить сайт с телефона: скорость, мобильная версия, есть ли кнопки WhatsApp/Telegram), а в шаге 5 делай упор на модернизацию вместо переделки с нуля.
- Если в таблице есть черновой «Готовый оффер» или описание слабых мест сайта — опирайся на эти факты, не противоречь им, но перепиши живым языком технаря.
- Если ниша не указана — определи её по названию компании.
- Если в данных есть имя владельца или контакта — используй его в шаге 2, иначе без имени.
- Ничего не выдумывай сверх данных."""


def _extract_json(text: str) -> dict:
    """Достаёт JSON из ответа модели (устойчиво к ```json-обёрткам и мусору)."""
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
    cleaned = re.sub(r"\s*```$", "", cleaned)

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # Ищем первый {...} балансом скобок
    start = cleaned.find("{")
    if start == -1:
        raise AIGenerationError("Нейросеть вернула ответ без JSON")
    depth = 0
    for i in range(start, len(cleaned)):
        if cleaned[i] == "{":
            depth += 1
        elif cleaned[i] == "}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(cleaned[start:i + 1])
                except json.JSONDecodeError:
                    break
    raise AIGenerationError("Не удалось разобрать JSON из ответа нейросети")


def generate_pitch(lead: dict) -> dict:
    """
    Генерирует оффер для лида. Возвращает dict с ключами
    hook / offer / objections / closing. Бросает AIGenerationError при сбое.
    """
    user_prompt = USER_PROMPT_TEMPLATE.format(
        name=lead.get("company_name") or "не указано",
        niche=lead.get("niche") or "не указана",
        city=lead.get("city") or "не указан",
        address=lead.get("address") or "—",
        website=lead.get("website") or "отсутствует",
        extra=(lead.get("extra_info") or "—")[:500],
    )

    payload = {
        "model": config.AI_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt}
        ],
        "temperature": 0.7,
        # Atria-Dawn-Preview — reasoning-модель: сначала «думает» в
        # reasoning_content, затем пишет ответ. Лимит должен покрывать
        # размышления плюс готовый шаблон разговора с возражениями,
        # иначе content приходит пустым с finish_reason="length".
        "max_tokens": 12000
    }
    headers = {
        "Authorization": f"Bearer {config.AI_API_KEY}",
        "Content-Type": "application/json"
    }

    try:
        response = httpx.post(
            f"{config.AI_API_URL}/chat/completions",
            json=payload,
            headers=headers,
            timeout=httpx.Timeout(config.AI_READ_TIMEOUT, connect=config.AI_CONNECT_TIMEOUT)
        )
    except httpx.HTTPError as e:
        raise AIGenerationError(f"Сеть недоступна: {e.__class__.__name__}")

    if response.status_code != 200:
        detail = response.text[:300] if response.text else "пустой ответ"
        raise AIGenerationError(f"API вернул {response.status_code}: {detail}")

    try:
        body = response.json()
        content = body["choices"][0]["message"]["content"]
    except (ValueError, KeyError, IndexError, TypeError):
        raise AIGenerationError("Неожиданный формат ответа API")

    if not content or not content.strip():
        raise AIGenerationError(
            "Нейросеть вернула пустой ответ: модель потратила весь лимит токенов на размышления. Повторите попытку."
        )

    parsed = _extract_json(content)

    result = {
        "hook": str(parsed.get("hook") or parsed.get("opening") or "").strip(),
        "offer": str(
            parsed.get("offer")
            or parsed.get("script")
            or parsed.get("call_script")
            or parsed.get("pitch")
            or ""
        ).strip(),
        "objections": str(parsed.get("objections") or parsed.get("objection") or "").strip(),
        "closing": str(parsed.get("closing") or parsed.get("close") or "").strip(),
    }

    # Если модель вернула текст не по полям — кладём всё в offer, чтобы не терять ответ
    if not any(result.values()):
        result["offer"] = content.strip()[:4000]

    return result


def is_configured() -> bool:
    return bool(config.AI_API_URL and config.AI_API_KEY and config.AI_MODEL)

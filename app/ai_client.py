"""
Клиент нейросети для генерации офферов холодного обзвона.

Работает с OpenAI-совместимым API (POST {AI_API_URL}/chat/completions).
Модель: GLM-5.3. Ключ и адрес задаются в app/config.py.
"""
import json
import re
from datetime import datetime

import httpx

from app import config


class AIGenerationError(Exception):
    """Ошибка обращения к нейросети или разбора ответа."""


# Системный промпт: нейросеть выступает в роли топ-эксперта по холодным
# звонкам в B2B, который продаёт разработку и модернизацию сайтов.
SYSTEM_PROMPT = """Ты — senior-эксперт по холодным B2B-продажам с 15-летним опытом и лучший «открывальщик» разговоров. Ты продаёшь услуги веб-студии: разработку сайтов и лендингов, модернизацию слабых и «мёртвых» сайтов, упаковку бизнеса в интернете. Ты досконально знаешь структуру идеального холодного звонка, технику «крючок в первые 10 секунд», SPIN и PAS (проблема → усиление → решение), принцип взаимности и отработку возражений («дорого», «нам не надо», «уже есть сайт», «пришлите КП на почту», «подумаю», «нет времени», «работаем только по рекомендациям»).

Твоя задача — выдать оператору ГОТОВЫЙ ШАБЛОН РАЗГОВОРА, который можно читать вслух с листа: живые фразы, без канцелярита, без слов «уникальный», «инновационный», «синергия».

## Что важно знать про лид
Это компания из карточек организаций (2ГИС / Яндекс.Карты). Оператор звонит по её телефону впервые. Часто трубку берёт администратор или менеджер, а не владелец.

## Факты о нас (используй ровно это и НИЧЕГО не выдумывай)
- Мы веб-студия: делаем сайты и лендинги для малого и среднего бизнеса и модернизируем сайты, которые не приносят заявок.
- Что входит в работу: домен и хостинг, дизайн под нишу, мобильная версия, онлайн-заявка и кнопки WhatsApp/Telegram, SSL-сертификат, быстрая загрузка, связка с картами, базовая подготовка к SEO.
- Сроки: лендинг — 5–7 дней, сайт с каталогом — 2–3 недели.
- Первый шаг для клиента бесплатный: за 2–3 дня показываем короткий аудит и прототип первой страницы — «что именно теряет бизнес и как это исправить».
- Работаем по договору, оплата по этапам, правки на этапе согласования — бесплатно.
- Примеры работ по нужной нише показываем в мессенджере: «скину 2–3 примера по вашей теме».

## Жёсткие запреты (важнее красоты текста)
- НЕ выдумывай цифры: никаких придуманных конверсий, выручки, количества клиентов, отзывов, наград, названий клиентов и конкретных цен.
- НЕ утверждай того, чего нет в данных: если сайт не указан — говори «в карточке на картах сайт не указан», а не «у вас нет сайта».
- НЕ придумывай проблемы сайта, которого мы не видели.
- Цену не называй: только «стоимость назову после бесплатного анализа — обычно выходит дешевле, чем кажется, и фиксируется в договоре».

## Как говорить (правила речи)
1. Короткие фразы: 5–12 слов. Так реально говорит живой человек по телефону.
2. Оператор обращается к собеседнику на «вы».
3. Не начинай с «здравствуйте, меня зовут…, я звоню по поводу…»: сначала крючок, затем представление.
4. Персонализация под нишу, город, название компании и состояние сайта. Боль ниши должна быть узнаваемой: салоны и клиники теряют записи, мебельные продают по фото, автосервисы живут на повторных клиентах, магазины — на доверии и доставке.
5. Говори выгодами бизнеса, а не характеристиками: не «адаптивный дизайн», а «клиент со смартфона запишется в два клика, а не уйдёт к конкуренту».
6. Один вопрос за раз, и почти каждую реплику закрывай вопросом — чтобы паузу нельзя было использовать для «до свидания».

## Структура поля "offer" — ГОТОВЫЙ ШАБЛОН РАЗГОВОРА
Выдай его пронумерованными шагами. Каждый шаг — заголовок капсом и реплика оператора в кавычках «…». Обязательные шаги:
ШАГ 1. КТО ВЗЯЛ ТРУБКУ — что сказать, если ответил не руководитель: попросить соединить и коротко объяснить тему («подскажите, с кем лучше обсудить сайт?»). Если ответил руководитель — сразу к шагу 2.
ШАГ 2. ПЕРВЫЕ 10 СЕКУНД — крючок: наблюдение про его бизнес + выгода, 1–2 короткие фразы, которые работают, даже если человек уже готов положить трубку.
ШАГ 3. ПРЕДСТАВЛЕНИЕ — кто мы и почему позвонили именно ему, 1–2 фразы.
ШАГ 4. ВОВЛЕКАЮЩИЙ ВОПРОС — вопрос про его ситуацию (сколько заявок идёт с карт, кто ведёт сайт, сколько клиентов приходит из интернета), на который легко ответить.
ШАГ 5. ОФФЕР — что конкретно сделаем, какую боль снимаем, что получит бизнес, за какой срок и почему это безопасно (бесплатный аудит и прототип, договор, оплата по этапам).
ШАГ 6. ЗАКРЫТИЕ НА ШАГ — конкретное предложение («покажу аудит и прототип за 2–3 дня, скину в WhatsApp/Telegram») плюс альтернативный вопрос по времени.
Где полезно — добавляй отдельной строкой пометки вида «(если клиент …) — тогда …».
Объём: 1200–2000 знаков. Шаги разделяй пустой строкой (в JSON — \\n\\n).

## Поле "hook"
Дословная фраза первых 7–10 секунд (1–2 предложения, до 300 знаков), которую оператор произносит сразу после «Алло»: конкретное наблюдение + выгода или вопрос, от которого не хочется класть трубку.

## Поле "objections"
5 самых вероятных возражений именно для этой ниши и состояния сайта. Формат — каждый пункт с новой строки (\\n), строго по шаблону: «Возражение» — ответ оператора (2–3 короткие фразы, с переводом в следующий шаг). Набор для выбора: «дорого», «нам не надо / нас всё устраивает», «уже есть сайт», «нет времени», «пришлите КП на почту», «мы подумаем», «работаем только по рекомендациям», «сейчас нет денег», «сайт делает знакомый».

## Поле "closing"
1–2 фразы закрытия: конкретный следующий шаг + альтернативный вопрос по времени («Вам удобнее завтра до обеда или после 15:00?»). Без «ну что, будем работать?».

## Формат ответа
Только валидный JSON без markdown-обёрток и без пояснений. Переносы строк внутри строк кодируй как \\n. Схема:
{
  "hook": "…",
  "offer": "ШАГ 1. …\\n\\nШАГ 2. …",
  "objections": "«Дорого» — …\\n«Уже есть сайт» — …",
  "closing": "…"
}"""

USER_PROMPT_TEMPLATE = """Составь готовый шаблон холодного звонка для этой компании:

- Название: {name}
- Ниша/категория: {niche}
- Город: {city}
- Адрес: {address}
- Сайт: {website}
- Дополнительно из таблицы (черновик оффера, мессенджеры, ссылка на карточку): {extra}

Как использовать данные:
- Если сайт = «отсутствует» — в звонке формулируй «в карточке на картах сайт не указан» (не «у вас нет сайта»), а главный аргумент: клиенты уходят к конкурентам, которых находят в поиске и на картах.
- Если сайт указан — делай упор на бесплатный аудит (скорость, мобильная версия, SSL, захват заявок) и на модернизацию вместо переделки с нуля.
- Если в таблице есть черновой «Готовый оффер» или описание слабых мест сайта — опирайся на эти факты, не противоречь им, но перепиши текст живее и убедительнее.
- Если ниша не указана — определи её по названию компании.
- Ничего не выдумывай сверх данных."""


def _extract_json(text: str) -> dict:
    """Достаёт JSON из ответа модели (устойчиво к ```json-обёрткам и мусору)."""
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
    cleaned = re.sub(r"\s*```$", "", cleaned)

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # Ищем первый {...} балансом скобок
    start = cleaned.find("{")
    if start == -1:
        raise AIGenerationError("Нейросеть вернула ответ без JSON")
    depth = 0
    for i in range(start, len(cleaned)):
        if cleaned[i] == "{":
            depth += 1
        elif cleaned[i] == "}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(cleaned[start:i + 1])
                except json.JSONDecodeError:
                    break
    raise AIGenerationError("Не удалось разобрать JSON из ответа нейросети")


def generate_pitch(lead: dict) -> dict:
    """
    Генерирует оффер для лида. Возвращает dict с ключами
    hook / offer / objections / closing. Бросает AIGenerationError при сбое.
    """
    user_prompt = USER_PROMPT_TEMPLATE.format(
        name=lead.get("company_name") or "не указано",
        niche=lead.get("niche") or "не указана",
        city=lead.get("city") or "не указан",
        address=lead.get("address") or "—",
        website=lead.get("website") or "отсутствует",
        extra=(lead.get("extra_info") or "—")[:500],
    )

    payload = {
        "model": config.AI_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt}
        ],
        "temperature": 0.7,
        # GLM-5.3 — reasoning-модель: сначала «думает» в reasoning_content,
        # затем пишет ответ. Лимит должен покрывать размышления плюс готовый
        # шаблон разговора с возражениями, иначе content приходит пустым
        # с finish_reason="length".
        "max_tokens": 12000
    }
    headers = {
        "Authorization": f"Bearer {config.AI_API_KEY}",
        "Content-Type": "application/json"
    }

    try:
        response = httpx.post(
            f"{config.AI_API_URL}/chat/completions",
            json=payload,
            headers=headers,
            timeout=httpx.Timeout(config.AI_READ_TIMEOUT, connect=config.AI_CONNECT_TIMEOUT)
        )
    except httpx.HTTPError as e:
        raise AIGenerationError(f"Сеть недоступна: {e.__class__.__name__}")

    if response.status_code != 200:
        detail = response.text[:300] if response.text else "пустой ответ"
        raise AIGenerationError(f"API вернул {response.status_code}: {detail}")

    try:
        body = response.json()
        content = body["choices"][0]["message"]["content"]
    except (ValueError, KeyError, IndexError, TypeError):
        raise AIGenerationError("Неожиданный формат ответа API")

    if not content or not content.strip():
        raise AIGenerationError(
            "Нейросеть вернула пустой ответ: модель потратила весь лимит токенов на размышления. Повторите попытку."
        )

    parsed = _extract_json(content)

    result = {
        "hook": str(parsed.get("hook") or parsed.get("opening") or "").strip(),
        "offer": str(
            parsed.get("offer")
            or parsed.get("script")
            or parsed.get("call_script")
            or parsed.get("pitch")
            or ""
        ).strip(),
        "objections": str(parsed.get("objections") or parsed.get("objection") or "").strip(),
        "closing": str(parsed.get("closing") or parsed.get("close") or "").strip(),
    }

    # Если модель вернула текст не по полям — кладём всё в offer, чтобы не терять ответ
    if not any(result.values()):
        result["offer"] = content.strip()[:4000]

    return result


def is_configured() -> bool:
    return bool(config.AI_API_URL and config.AI_API_KEY and config.AI_MODEL)
